#!/bin/sh
# ============================================================================
# 容器入口：先应用数据库迁移，再启动服务
#
# 为什么迁移放这里而不是构建期：
#  - 构建期不该依赖真实数据库（构建环境通常拿不到生产库）
#  - 容器重启/滚动更新时自动补齐 schema，避免「代码更新了但表没更新」
# 迁移失败时**不启动服务**：宁可让容器起不来（明确失败），
# 也不要让旧 schema 配新代码跑出难排查的运行时错误。
# ============================================================================
set -eu

echo "[entrypoint] 应用数据库迁移…"
# DATABASE_URL 由运行时注入，绝不写进镜像。
# 用镜像内已安装的 CLI（不联网下载）。
./node_modules/.bin/prisma migrate deploy --schema=./prisma/schema.prisma

echo "[entrypoint] 启动 Next.js 服务 (port ${PORT:-3000})…"
exec node server.js
